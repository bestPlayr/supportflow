create table app_users (
 id bigint generated by default as identity primary key,
 email varchar(254) not null unique, password varchar(100) not null,
 role varchar(20) not null, skills varchar(200) not null,
 capacity integer not null, available boolean not null
);
create table tickets (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 subject varchar(200) not null, description varchar(10000) not null,
 customer_id bigint not null references app_users(id),
 assignee_id bigint references app_users(id), category varchar(30) not null,
 status varchar(30) not null, priority varchar(20) not null,
 created_at timestamp with time zone not null, due_at timestamp with time zone not null,
 first_response_at timestamp with time zone, escalated boolean not null,
 ai_state varchar(20) not null, attempts integer not null,
 next_attempt_at timestamp with time zone not null,
 summary varchar(2000), draft varchar(4000), ai_source varchar(20),
 last_error varchar(200)
);
create index idx_ticket_jobs on tickets(ai_state, next_attempt_at);
create index idx_ticket_assignee on tickets(assignee_id, status);
create index idx_ticket_customer on tickets(customer_id);
create table messages (
 id bigint generated by default as identity primary key,
 ticket_id bigint not null references tickets(id),
 author_id bigint not null references app_users(id),
 body varchar(4000) not null, created_at timestamp with time zone not null
);
create table audit_events (
 id bigint generated by default as identity primary key,
 ticket_id bigint not null references tickets(id),
 actor varchar(254) not null, action varchar(100) not null,
 detail varchar(1000) not null, created_at timestamp with time zone not null
);
create table knowledge_articles (
 id bigint generated by default as identity primary key,
 title varchar(200) not null, category varchar(30) not null,
 content varchar(4000) not null
);
